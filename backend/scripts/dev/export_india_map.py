"""Convert the dashboard's India map (frontend/src/lib/indiaMap.ts) to JSON for the PDF export.

The dashboard map is generated by frontend/scripts/build_india_map.py. Run this after regenerating it:
    python backend/scripts/dev/export_india_map.py
"""

import json
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[3]
SOURCE = REPO_ROOT / "frontend" / "src" / "lib" / "indiaMap.ts"
TARGET = REPO_ROOT / "backend" / "app" / "reports" / "india_map.json"
POINT = re.compile(r"(-?\d+(?:\.\d+)?),(-?\d+(?:\.\d+)?)")


def rings(path: str) -> list[list[list[float]]]:
    """The map uses only absolute M/L/Z commands, so each M starts a new closed ring."""
    return [
        [[float(x), float(y)] for x, y in POINT.findall(part)]
        for part in path.split("M")
        if part.strip()
    ]


def main() -> None:
    text = SOURCE.read_text(encoding="utf-8")
    width, height = (
        float(v) for v in re.search(r"width: ([\d.]+), height: ([\d.]+)", text).groups()
    )
    states = [
        {"name": s["name"], "rings": rings(s["d"])}
        for s in (json.loads(m) for m in re.findall(r"^\s+(\{\"name\".*\}),?$", text, re.M))
    ]
    TARGET.write_text(
        json.dumps({"width": width, "height": height, "states": states}, separators=(",", ":")),
        encoding="utf-8",
    )
    print(f"wrote {len(states)} states to {TARGET.relative_to(REPO_ROOT)}", file=sys.stderr)


if __name__ == "__main__":
    main()
