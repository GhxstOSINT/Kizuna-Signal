"""Build frontend/src/lib/indiaMap.ts: simplified SVG paths for India's states and union territories.

Source: datta07/INDIAN-SHAPEFILES (INDIA_STATES.geojson), downloaded to the path given as argv[1].
    curl -L -o /tmp/india_states.geojson \
      https://raw.githubusercontent.com/datta07/INDIAN-SHAPEFILES/master/INDIA/INDIA_STATES.geojson
    python frontend/scripts/build_india_map.py /tmp/india_states.geojson

Names are mapped to the ones the backend uses (backend/app/ml/states.py).
"""
import json
import math
import sys
from pathlib import Path

RENAME = {
    "Andaman & Nicobar": "Andaman and Nicobar Islands",
    "Jammu & Kashmir": "Jammu and Kashmir",
    "Dadra & Nagar Haveli": "Dadra and Nagar Haveli and Daman and Diu",
    "Daman & Diu": "Dadra and Nagar Haveli and Daman and Diu",
}
WIDTH = 620.0
TOLERANCE = 0.9  # px in the output space
MIN_RING_AREA = 6.0  # px^2; drops specks but keeps every state's largest ring
MARKER_AREA = 200.0  # px^2; regions smaller than this also get a hoverable dot


def project(lon, lat):
    # Equirectangular, scaled at India's mid latitude so shapes are not stretched.
    return lon * math.cos(math.radians(22)), -lat


def simplify(points, tol):
    if len(points) < 4:
        return points
    keep = [False] * len(points)
    keep[0] = keep[-1] = True
    stack = [(0, len(points) - 1)]
    while stack:
        a, b = stack.pop()
        (x1, y1), (x2, y2) = points[a], points[b]
        dx, dy = x2 - x1, y2 - y1
        norm = math.hypot(dx, dy) or 1e-12
        far, far_d = -1, 0.0
        for i in range(a + 1, b):
            d = abs(dy * (points[i][0] - x1) - dx * (points[i][1] - y1)) / norm
            if d > far_d:
                far, far_d = i, d
        if far_d > tol:
            keep[far] = True
            stack += [(a, far), (far, b)]
    return [p for p, k in zip(points, keep) if k]


def simplify_ring(ring, tol):
    # Rings are closed (first == last), which breaks the distance-to-chord test; split in two.
    if len(ring) < 8:
        return ring
    mid = len(ring) // 2
    return simplify(ring[: mid + 1], tol)[:-1] + simplify(ring[mid:], tol)


def area(ring):
    return abs(sum(x1 * y2 - x2 * y1 for (x1, y1), (x2, y2) in zip(ring, ring[1:] + ring[:1]))) / 2


def main(src):
    data = json.loads(Path(src).read_text())
    rings_by_state: dict[str, list] = {}
    for feature in data["features"]:
        name = feature["properties"]["STNAME_SH"].strip()
        name = RENAME.get(name, name)
        geometry = feature["geometry"]
        polygons = geometry["coordinates"] if geometry["type"] == "MultiPolygon" else [geometry["coordinates"]]
        rings_by_state.setdefault(name, []).extend(
            [project(lon, lat) for lon, lat in polygon[0]] for polygon in polygons
        )

    xs = [x for rings in rings_by_state.values() for ring in rings for x, _ in ring]
    ys = [y for rings in rings_by_state.values() for ring in rings for _, y in ring]
    min_x, max_x, min_y, max_y = min(xs), max(xs), min(ys), max(ys)
    scale = WIDTH / (max_x - min_x)
    height = round((max_y - min_y) * scale, 1)

    states = []
    for name, rings in sorted(rings_by_state.items()):
        scaled = [[((x - min_x) * scale, (y - min_y) * scale) for x, y in ring] for ring in rings]
        scaled.sort(key=area, reverse=True)
        kept = [simplify_ring(r, TOLERANCE) for i, r in enumerate(scaled) if i == 0 or area(r) >= MIN_RING_AREA]
        kept = [r for r in kept if len(r) >= 3]
        d = "".join("M" + "L".join(f"{x:.1f},{y:.1f}" for x, y in ring) + "Z" for ring in kept)
        all_x = [x for ring in scaled for x, _ in ring]
        all_y = [y for ring in scaled for _, y in ring]
        entry = {"name": name, "d": d}
        if sum(area(r) for r in scaled) < MARKER_AREA:
            # Centre of the largest piece, so a split region (Dadra/Daman) still gets one dot on land.
            big = scaled[0]
            entry["marker"] = [round(sum(x for x, _ in big) / len(big), 1), round(sum(y for _, y in big) / len(big), 1)]
        states.append(entry)

    out = Path(__file__).resolve().parents[1] / "src" / "lib" / "indiaMap.ts"
    body = ",\n".join("  " + json.dumps(s, ensure_ascii=False) for s in states)
    out.write_text(
        "// Generated by frontend/scripts/build_india_map.py. Do not edit by hand.\n"
        "export interface MapState { name: string; d: string; marker?: [number, number] }\n\n"
        f"export const INDIA_MAP = {{ width: {WIDTH:.0f}, height: {height}, states: [\n{body},\n] as MapState[] }}\n"
    )
    print(out, len(states), "states", out.stat().st_size // 1024, "KB")


main(sys.argv[1])
