"""Generate frontend/src/i18n/titles.ts: English anime title -> Japanese title.

The 300 reference titles carry a `japanese_title` column in data/tables/titles_features.csv; the demo
catalogue in backend/app/services/comparables.py adds a few more. Keys are normalised (lowercase, letters
and digits only) so "Your Name." and "Your Name" resolve to the same entry.

    python frontend/scripts/build_title_names.py
"""
from __future__ import annotations

import csv
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "data" / "tables" / "titles_features.csv"
TARGET = ROOT / "frontend" / "src" / "i18n" / "titles.ts"

# Demo-catalogue titles that are named differently from the dataset.
EXTRA = {
    "Jujutsu Kaisen": "呪術廻戦",
    "Demon Slayer": "鬼滅の刃",
    "Death Note": "DEATH NOTE",
    "Spy x Family": "SPY×FAMILY",
    "Your Name": "君の名は。",
    "Attack on Titan": "進撃の巨人",
    "Haikyu": "ハイキュー!!",
    "Naruto": "NARUTO -ナルト-",
}


def normalise(name: str) -> str:
    return re.sub(r"[^a-z0-9]", "", name.lower())


def main() -> None:
    names: dict[str, str] = {}
    with SOURCE.open(encoding="utf-8-sig", newline="") as handle:
        for row in csv.DictReader(handle):
            english = row["name_en"].strip()
            japanese = row["japanese_title"].strip()
            key = normalise(english)
            if key and japanese and key not in names:
                names[key] = japanese
    for english, japanese in EXTRA.items():
        names.setdefault(normalise(english), japanese)

    lines = [
        "// Generated by frontend/scripts/build_title_names.py; do not edit by hand.",
        "// Keys are English titles reduced to lowercase letters and digits.",
        "export const titleNames: Record<string, string> = {",
    ]
    for key in sorted(names):
        value = names[key].replace("\\", "\\\\").replace("'", "\\'")
        lines.append(f"  '{key}': '{value}',")
    lines.append("}")
    TARGET.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {len(names)} titles to {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
